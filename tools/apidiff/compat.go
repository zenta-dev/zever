package main

import (
	"fmt"
	"io"
	"os"
	"strings"
)

// compatNote overrides the default policy note for modules whose release
// story differs from the plain Core tier.
var compatNote = map[string]string{
	"dsl": "compile-time only, no release version (schema v1/v2 are API versions)",
}

// compatMatrix renders the generated compatibility-matrix doc: one row per
// Core-tier module with the tier and the per-release-type policy. The patch
// column is enforced by --check-patch, the minor/major column by the
// apidiff gate itself. Rendering is deterministic: the same coreModules
// order always produces the same bytes, so --check-compat-matrix can
// compare the committed doc exactly.
func compatMatrix() string {
	var b strings.Builder
	b.WriteString("---\n")
	b.WriteString("title: Compatibility matrix\n")
	b.WriteString("description: Which modules the API gates protect, and what may break per release type.\n")
	b.WriteString("---\n")
	b.WriteString("\n")
	b.WriteString("{/* Code generated by `go run ./tools/apidiff --compat-matrix <file>`. DO NOT EDIT. */}\n")
	b.WriteString("\n")
	b.WriteString("Core modules diff against `<dir>/vX.Y.Z` (`make apidiff`). Patches via `go run ./tools/apidiff --check-patch`. Pre-1.0 Extended (rest of STABILITY.md) may break (release notes).\n")
	b.WriteString("\n")
	b.WriteString("| Module | Import path | Tier | Patch (x.y.Z) | Minor/major (pre-1.0) |\n")
	b.WriteString("|---|---|---|---|---|\n")
	for _, dir := range coreModules {
		note := compatNote[dir]
		if note == "" {
			note = "standard Core policy"
		}
		fmt.Fprintf(&b, "| `%s` | `%s%s` | Core | no breaking changes | breaking allowed with a `**Breaking:**` entry naming the module | {/* %s */}\n",
			dir, zeverModulePrefix, dir, note)
	}
	return b.String()
}

// runCompatMatrix implements --compat-matrix: write the rendered doc to file.
func runCompatMatrix(file string, stdout io.Writer) int {
	if err := os.WriteFile(file, []byte(compatMatrix()), 0o644); err != nil { // docs are world-readable
		fmt.Fprintf(stdout, "apidiff: write %s: %v\n", file, err)
		return 1
	}
	fmt.Fprintf(stdout, "apidiff: wrote compatibility matrix for %d modules to %s\n", len(coreModules), file)
	return 0
}

// runCheckCompatMatrix implements --check-compat-matrix: exit 1 when file
// differs from the rendered doc.
func runCheckCompatMatrix(file string, stdout io.Writer) int {
	raw, err := os.ReadFile(file)
	if err != nil {
		fmt.Fprintf(stdout, "apidiff: read %s: %v\n", file, err)
		return 1
	}
	if want := compatMatrix(); string(raw) != want {
		fmt.Fprintf(stdout, "apidiff: %s differs from the generated matrix; run: go run ./tools/apidiff --compat-matrix %s\n", file, file)
		return 1
	}
	fmt.Fprintf(stdout, "apidiff: %s matches the generated matrix (%d modules)\n", file, len(coreModules))
	return 0
}
