// TestSchemaHashDeterministic proves the schema hash is stable for identical
// inputs and changes when any schema byte changes: the version+hash header
// is only a useful provenance stamp if the hash actually fingerprints the
// schema.
func TestSchemaHashDeterministic(t *testing.T) {
	t.Parallel()

	files := map[string]string{"a.zen": inspectUserSchema}
	first := schemaHashOf(files)

	if got := schemaHashOf(map[string]string{"a.zen": inspectUserSchema}); got != first {
		t.Fatalf("schemaHashOf not deterministic: %q vs %q", first, got)
	}

	if first == "" {
		t.Fatal("schemaHashOf returned empty hash")
	}

	changed := schemaHashOf(map[string]string{"a.zen": inspectUserSchema + "\n"})
	if changed == first {
		t.Fatal("schemaHashOf did not change when schema content changed")
	}

	renamed := schemaHashOf(map[string]string{"b.zen": inspectUserSchema})
	if renamed == first {
		t.Fatal("schemaHashOf did not change when schema path changed")
	}
}

// TestStampedHeaderContainsVersionAndHash proves every generated file header
// carries the CLI version and the schema hash, so a reader can tell which
// zever release produced a file and which schema revision it came from.
func TestStampedHeaderContainsVersionAndHash(t *testing.T) {
	t.Parallel()

	hash := "deadbeef0123456789abcdef0123456789abcdef0123456789abcdef01234567"

	for _, file := range []string{"app/types.go", "schema.proto", "schema.hcl"} {
		got := stampGeneratedFile("gogen", file, []byte("// Code generated by something. DO NOT EDIT.\n\npackage app\n"), hash)
		text := string(got)

		if !strings.Contains(text, "v"+cliVersion) {
			t.Errorf("%s: stamped header missing version %q:\n%s", file, cliVersion, text)
		}

		if !strings.Contains(text, hash) {
			t.Errorf("%s: stamped header missing schema hash:\n%s", file, text)
		}

		if !strings.Contains(text, "package app") {
			t.Errorf("%s: stamping dropped the original body:\n%s", file, text)
		}
	}
}

// TestStampedJSONCarriesProvenance proves .json outputs (which cannot carry
// a // comment without breaking parsers) embed the version+hash in a
// top-level x-zever-generated block instead, and stay valid JSON.
func TestStampedJSONCarriesProvenance(t *testing.T) {
	t.Parallel()

	hash := "deadbeef0123456789abcdef0123456789abcdef0123456789abcdef01234567"
	raw := []byte("{\n  \"openapi\": \"3.0.3\",\n  \"info\": {}\n}\n")

	got := stampGeneratedFile("openapi", "openapi.json", raw, hash)

	var doc map[string]any
	if err := json.Unmarshal(got, &doc); err != nil {
		t.Fatalf("stamped openapi.json is not valid JSON: %v\n%s", err, got)
	}

	block, ok := doc["x-zever-generated"].(map[string]any)
	if !ok {
		t.Fatalf("stamped openapi.json missing x-zever-generated block:\n%s", got)
	}

	if block["version"] != "v"+cliVersion {
		t.Errorf("version = %v, want %q", block["version"], "v"+cliVersion)
	}

	if block["schema"] != "sha256:"+hash {
		t.Errorf("schema = %v, want sha256 hash", block["schema"])
	}

	if block["backend"] != "openapi" {
		t.Errorf("backend = %v, want openapi", block["backend"])
	}
}

// TestStampSkipsAnnotationsCompanion proves the verbatim
// zever/annotations.proto companion copy is never rewritten: it is vendored
// wire-stable API, not schema-derived output.
func TestStampSkipsAnnotationsCompanion(t *testing.T) {
	t.Parallel()

	raw := []byte("// verbatim companion\npackage zever;\n")
	got := stampGeneratedFile("proto", "zever/annotations.proto", raw, "abc123")

	if !bytes.Equal(got, raw) {
		t.Fatalf("annotations companion was rewritten:\n%s", got)
	}
}
