// Contributor-tooling files written into scaffolded projects by opt-in
// `zever add` recipes (docker, ci, lint, compose) or shipped by default in
// earlier scaffold generations (Makefile, golangci, editorconfig,
// dependabot). They are plain files the project owns from day one; zever
// never rewrites them.

// renderNewMakefile returns the scaffolded Makefile. backends is the
// --backend value the project's `zever compile` runs use (same as CI).
func renderNewMakefile(backends string) string {
	var b strings.Builder

	b.WriteString("# Scaffolded by `zever new`. Common development tasks.\n")
	b.WriteString("#\n")
	b.WriteString("# `generate` needs the zever CLI on PATH:\n")
	b.WriteString("#   go install github.com/zenta-dev/zever/cmd/zever@latest\n")
	fmt.Fprintf(&b, "\nSCHEMA   ?= schema/*.zen\nBACKENDS ?= %s\n", backends)
	b.WriteString("\n.DEFAULT_GOAL := help\n")

	targets := []struct{ name, help, recipe string }{
		{"generate", "Regenerate derived code from the schema", "zever compile --backend=$(BACKENDS) --out ./generated $(SCHEMA)"},
		{"check-generated", "Fail when committed generated/ drifts from the schema", "zever compile --check --backend=$(BACKENDS) --out ./generated $(SCHEMA)"},
		{"build", "Build every package", "go build ./..."},
		{"test", "Run the tests", "go test ./..."},
		{"test-race", "Run the tests with the race detector", "go test -race ./..."},
		{"vet", "Run go vet", "go vet ./..."},
		{"fmt", "Check gofmt formatting", "@test -z \"$$(gofmt -l .)\" || { gofmt -l .; echo 'gofmt: files need formatting (run gofmt -w .)'; exit 1; }"},
		{"lint", "Run golangci-lint (https://golangci-lint.run)", "golangci-lint run ./..."},
		{"run", "Run the server locally", "go run ./cmd/server"},
		{"docker", "Build the container image", "docker build -t app ."},
	}

	phony := make([]string, 0, len(targets)+1)

	for _, t := range targets {
		phony = append(phony, t.name)
	}

	phony = append(phony, "help")
	fmt.Fprintf(&b, "\n.PHONY: %s\n", strings.Join(phony, " "))

	for _, t := range targets {
		deps := ""
		if t.name == "build" || t.name == "test" || t.name == "test-race" || t.name == "vet" {
			deps = " generate"
		}

		fmt.Fprintf(&b, "\n%s:%s ## %s\n\t%s\n", t.name, deps, t.help, t.recipe)
	}

	b.WriteString("\nhelp: ## List targets\n")
	b.WriteString("\t@grep -E '^[a-zA-Z_-]+:.*## ' $(MAKEFILE_LIST) | sed -E 's/:[^#]*## /\\t/' | sort\n")

	return b.String()
}

