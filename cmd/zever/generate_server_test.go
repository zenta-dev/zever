// TestDevEnvTable proves devEnv trims and case-folds ZEVER_ENV and agrees
// with core/crypto.DevKeyAllowed on the same input.
func TestDevEnvTable(t *testing.T) {
	cases := []struct {
		v    string
		want bool
	}{
		{" Dev ", true},
		{"DEVELOPMENT", true},
		{"test\n", true},
		{"prod", false},
		{"", false},
	}
	for _, c := range cases {
		v, want := c.v, c.want
		t.Setenv("ZEVER_ENV", v)

		if got := devEnv(); got != want {
			t.Errorf("devEnv() with ZEVER_ENV=%q = %v, want %v", v, got, want)
		}

		if got := crypto.DevKeyAllowed(crypto.Options{}); got != want {
			t.Errorf("DevKeyAllowed with ZEVER_ENV=%q = %v, want %v", v, got, want)
		}
	}
}

// --- shared scaffolding test helpers (server, worker and seed) ---
//
// validateGoSyntax and readGenerated are owned by the generate wave; other
// command-test waves reuse them without redefining. writeGoMod is
// generate-local.

// writeGoMod writes a minimal go.mod into dir, the precondition every
// entrypoint scaffold has: the generated file imports the target project's own
// internal/app package, so it must know that project's module path.
func writeGoMod(t *testing.T, dir, modulePath string) {
	t.Helper()

	content := "module " + modulePath + "\n\ngo 1.24\n"

	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(content), 0o600); err != nil {
		t.Fatalf("write go.mod: %v", err)
	}
}

// validateGoSyntax proves content parses as syntactically valid Go and is
// already gofmt-formatted, mirroring the zenorm backend's own generated
// -code check. It only checks syntax; it never resolves imported packages.
func validateGoSyntax(t *testing.T, filename string, content []byte) {
	t.Helper()

	fset := token.NewFileSet()

	if _, err := parser.ParseFile(fset, filename, content, parser.AllErrors); err != nil {
		t.Fatalf("go/parser failed to parse generated file %s: %v\n--- content ---\n%s", filename, err, content)
	}

	formatted, err := format.Source(content)
	if err != nil {
		t.Fatalf("go/format.Source failed on generated file %s: %v", filename, err)
	}

	if string(formatted) != string(content) {
		t.Fatalf("generated file %s is not gofmt-formatted:\n--- got ---\n%s\n--- formatted ---\n%s",
			filename, content, formatted)
	}
}

// readGenerated reads a scaffolded file and asserts it is valid, gofmt-clean Go.
func readGenerated(t *testing.T, path string) string {
	t.Helper()

	data, err := os.ReadFile(path) // test fixture path
	if err != nil {
		t.Fatalf("expected a scaffold at %q: %v", path, err)
	}

	validateGoSyntax(t, path, data)

	return string(data)
}

// --- generate server ---

func TestRunGenerateServer(t *testing.T) {
	dir := t.TempDir()
	withWorkingDir(t, dir)
	writeGoMod(t, dir, "example.com/shop")

	if err := runGenerateServer(nil); err != nil {
		t.Fatalf("runGenerateServer: %v", err)
	}

	main := readGenerated(t, filepath.Join(dir, "cmd", "server", "main.go"))

	for _, fragment := range []string{
		`"example.com/shop/internal/app"`,
		`"github.com/zenta-dev/zever/serve"`,
		"func main()",
		`flag.String("addr"`,
		`flag.String("grpc-addr"`,
		"serve.Main(app.Providers(), modules, opts...)",
		`fmt.Fprintln(os.Stderr, "server:", err)`,
		"os.Exit(1)",
	} {
		if !strings.Contains(main, fragment) {
			t.Fatalf("server main.go lacks %q:\n%s", fragment, main)
		}
	}

	// The wrapper is thin by contract: boot behavior (listeners, TLS,
	// health, readiness, rate limiting, reflection, pprof, SIGHUP, doctor)
	// lives in the serve library, never in generated text. The grpcWired
	// gate keeps `zever dev -grpc-addr` green on scaffolds that never
	// wired auth+permission.
	if !strings.Contains(main, "if !grpcWired() {") {
		t.Fatalf("server main.go lacks the grpcWired gate:\n%s", main)
	}

	for _, unwanted := range []string{
		"grpc.NewServer",
		"http.ListenAndServe",
		"reflection.Register",
		"RateLimit",
		"middleware.",
		"healthpb.",
	} {
		if strings.Contains(main, unwanted) {
			t.Fatalf("server main.go must not contain %q (serve owns it):\n%s", unwanted, main)
		}
	}

	// With no schema the wiring file still renders: the schema-hash stamp
	// (empty-schema hash) and nothing else -- no imports without modules.
	modules := readGenerated(t, filepath.Join(dir, "internal", "app", "modules.go"))

	for _, fragment := range []string{
		"package app",
		"// Code generated by zever generate server v",
		"; DO NOT EDIT.",
		"// schema-hash: sha256:",
	} {
		if !strings.Contains(modules, fragment) {
			t.Fatalf("modules.go lacks %q:\n%s", fragment, modules)
		}
	}

	for _, unwanted := range []string{
		`"github.com/zenta-dev/zever/serve"`,
		`"github.com/zenta-dev/zever/container"`,
	} {
		if strings.Contains(modules, unwanted) {
			t.Fatalf("modules.go must not import %q with no schema:\n%s", unwanted, modules)
		}
	}

	// The app package is scaffolded alongside it when the project has none.
	app := readGenerated(t, filepath.Join(dir, "internal", "app", "app.go"))

	for _, fragment := range []string{
		"package app",
		// The floor is log + router only: one Ref var plus one
		// container.Provide entry per selection -- the container wires
		// nothing itself. No blank imports, no bundle imports.
		`logslog "github.com/zenta-dev/zever/adapters/log/slog"`,
		`routerstdhttp "github.com/zenta-dev/zever/adapters/router/stdhttp"`,
		"var Log = log.DefaultRef()",
		"container.Provide(",
		"func New() (*container.Container, error)",
		"func Providers() []container.Provider",
	} {
		if !strings.Contains(app, fragment) {
			t.Fatalf("app.go lacks %q:\n%s", fragment, app)
		}
	}

	for _, dropped := range []string{
		`_ "github.com/zenta-dev/zever/`,
		`"github.com/zenta-dev/zever/container/adapters/`,
		`"github.com/zenta-dev/zever/adapters/auth/jwt"`,
		`"github.com/zenta-dev/zever/adapters/db/sqlite"`,
		`"github.com/zenta-dev/zever/adapters/scheduler/embedded"`,
	} {
		if strings.Contains(app, dropped) {
			t.Fatalf("app.go must not contain %q:\n%s", dropped, app)
		}
	}

	assertGolden(t, "generate_server_main_default.golden", []byte(main))
	assertGolden(t, "generate_server_app.golden", []byte(app))
	assertGolden(t, "generate_server_modules_empty.golden", []byte(modules))
}

// TestRunGenerateServerIgnoresServerEnv proves the generated entrypoint is
// env-independent: reflection/TLS/rate-limit knobs now live in the serve
// library (read at boot), never in generated text, so server env changes do
// not alter a single generated byte.
func TestRunGenerateServerIgnoresServerEnv(t *testing.T) {
	for _, env := range []struct{ key, val string }{
		{"GRPC_REFLECTION", "true"},
		{"ZEVER_ENV", "dev"},
	} {
		t.Run(env.key, func(t *testing.T) {
			dir := t.TempDir()
			withWorkingDir(t, dir)
			writeGoMod(t, dir, "example.com/shop")
			t.Setenv(env.key, env.val)

			if err := runGenerateServer(nil); err != nil {
				t.Fatalf("runGenerateServer: %v", err)
			}

			main := readGenerated(t, filepath.Join(dir, "cmd", "server", "main.go"))

			for _, unwanted := range []string{"reflection.Register", "RateLimit", "tls.LoadX509KeyPair"} {
				if strings.Contains(main, unwanted) {
					t.Fatalf("server main.go must not contain %q with %s=%s:\n%s", unwanted, env.key, env.val, main)
				}
			}
		})
	}
}

func TestRunGenerateServerRefusesToClobberWithoutForce(t *testing.T) {
	dir := t.TempDir()
	withWorkingDir(t, dir)
	writeGoMod(t, dir, "example.com/shop")

	path := filepath.Join(dir, "cmd", "server", "main.go")

	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatalf("mkdir: %v", err)
	}

	const handwritten = "package main\n\nfunc main() {}\n"

	if err := os.WriteFile(path, []byte(handwritten), 0o600); err != nil {
		t.Fatalf("write: %v", err)
	}

	err := runGenerateServer(nil)
	if err == nil {
		t.Fatalf("expected an error for an existing entrypoint")
	}

	if !strings.Contains(err.Error(), "--force") {
		t.Fatalf("error does not mention --force: %v", err)
	}

	if got := readFile(t, path); got != handwritten {
		t.Fatalf("hand-written file was clobbered: %q", got)
	}

	// --force overwrites it.
	if err := runGenerateServer([]string{"--force"}); err != nil {
		t.Fatalf("runGenerateServer --force: %v", err)
	}

	if got := readFile(t, path); got == handwritten {
		t.Fatalf("--force did not overwrite the entrypoint")
	}
}

