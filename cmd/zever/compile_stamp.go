// schemaHashOf fingerprints the loaded schema sources: the sha256 hex digest
// over sorted "path NUL content NUL" pairs, so the same schema bytes always
// yield the same hash and any byte change (or rename) changes it. It feeds
// the generated-file provenance stamp (see stampGeneratedFile) and lets a
// reader tell which schema revision a committed file came from.
func schemaHashOf(files map[string]string) string {
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}

	sort.Strings(names)

	sum := sha256.New()

	for _, name := range names {
		sum.Write([]byte(name))
		sum.Write([]byte{0})
		sum.Write([]byte(files[name]))
		sum.Write([]byte{0})
	}

	return hex.EncodeToString(sum.Sum(nil))
}

// generatedStampLine is the provenance header prepended to every
// schema-derived generated file: the CLI release that produced it plus the
// schema hash it was compiled from. The version is deliberate: a reader can
// tell which release produced a file, and --check reports (but tolerates) a
// version-only difference (see normalizeStampVersion and --strict).
func generatedStampLine(hash string) string {
	return fmt.Sprintf("// Code generated by zever v%s; DO NOT EDIT.\n// schema-hash: sha256:%s", buildVersion, hash)
}

// stampGeneratedFile returns content stamped with the schema provenance for
// backend/path: comment-capable files (.go, .proto, .hcl, ...) gain the
// generatedStampLine header above the backend's own header (kept verbatim,
// so backend goldens and protoc headers survive untouched); .json outputs
// cannot carry a comment without breaking parsers, so they gain a top-level
// x-zever-generated block instead (a legal OpenAPI extension, and part of
// zever's own MCP manifest shape). The verbatim
// zever/annotations.proto companion copy is wire-stable vendored API, not
// schema-derived output, and is returned untouched.
func stampGeneratedFile(backend, path string, content []byte, hash string) []byte {
	if path == "zever/annotations.proto" || strings.HasSuffix(path, "/zever/annotations.proto") {
		return content
	}

	if strings.HasSuffix(path, ".json") {
		return stampGeneratedJSON(backend, content, hash)
	}

	line := generatedStampLine(hash)

	// Assembled via bytes.Buffer rather than a pre-sized make: summing
	// attacker-influenced lengths for an allocation size is an integer
	// overflow hazard (CodeQL), and the two writes below stay linear
	// anyway.
	var stamped bytes.Buffer

	stamped.WriteString(line + "\n")
	stamped.Write(content)

	return stamped.Bytes()
}

// marshalStampJSON renders doc as pretty-printed JSON with two-space indent
// plus no trailing newline (the caller appends it), matching the backends'
// own encoding. It uses codec.MarshalIndentCompat (Deterministic + 2-space +
// HTML/JS escaping), byte-identical to the previous encoding/json
// MarshalIndent output, so `zever generate` stays idempotent and --check
// passes unchanged.
func marshalStampJSON(doc map[string]any) ([]byte, error) {
	return codec.MarshalIndentCompat(doc)
}

// stampGeneratedJSON embeds the provenance block into a JSON generated file
// (see stampGeneratedFile). Output is two-space indented JSON plus a
// trailing newline, matching the backends' own encoding. Content that
// does not decode as a JSON object is returned byte-identical rather than
// corrupted.
func stampGeneratedJSON(backend string, content []byte, hash string) []byte {
	var doc map[string]any

	if err := codec.Unmarshal(content, &doc); err != nil || doc == nil {
		return content
	}

	doc["x-zever-generated"] = map[string]any{
		"backend": backend,
		"schema":  "sha256:" + hash,
		"version": "v" + buildVersion,
	}

	stamped, err := marshalStampJSON(doc)
	if err != nil {
		return content
	}

	return append(stamped, '\n')
}

// stampGeneratedOutputs stamps every backend output (see
// stampGeneratedFile) with the hash of the loaded schema files, returning a
// fresh map: compile.Compile's own result is never mutated.
func stampGeneratedOutputs(files map[string]string, outputs map[string]map[string][]byte) map[string]map[string][]byte {
	hash := schemaHashOf(files)

	stamped := make(map[string]map[string][]byte, len(outputs))

	for backend, backendFiles := range outputs {
		stampedFiles := make(map[string][]byte, len(backendFiles))

		for path, content := range backendFiles {
			stampedFiles[path] = stampGeneratedFile(backend, path, content, hash)
		}

		stamped[backend] = stampedFiles
	}

	return stamped
}

// checkGeneratedOutputs compares stamped fresh-compile outputs against the
// committed tree under outDir, returning one sorted "backend/path (reason)"
// entry per drifted file: missing (never generated), differs (stale bytes),
// or extra (on disk but no longer produced). A file whose bytes differ only
// in the stamped CLI version is not drift: it is returned in stampOnly
// instead, since a zever upgrade alone changes no generated content (the
// schema hash and every other byte still compare exactly). An empty drift
// return means the tree is up to date. It performs no writes.
func checkGeneratedOutputs(outDir string, outputs map[string]map[string][]byte) (drift, stampOnly []string) {
	backends := make([]string, 0, len(outputs))
	for backend := range outputs {
		backends = append(backends, backend)
	}

	sort.Strings(backends)

	for _, backend := range backends {
		backendFiles := outputs[backend]

		names := make([]string, 0, len(backendFiles))
		for name := range backendFiles {
			names = append(names, name)
		}

		sort.Strings(names)

		for _, name := range names {
			dest := filepath.Join(outDir, backend, name)

			disk, err := os.ReadFile(dest)
			if err != nil {
				drift = append(drift, filepath.Join(backend, name)+" (missing)")

				continue
			}

			switch {
			case bytes.Equal(disk, backendFiles[name]):
			case bytes.Equal(normalizeStampVersion(name, disk), normalizeStampVersion(name, backendFiles[name])):
				stampOnly = append(stampOnly, filepath.Join(backend, name))
			default:
				drift = append(drift, filepath.Join(backend, name)+" (differs)")
			}
		}

		for _, extra := range extraGeneratedFiles(filepath.Join(outDir, backend), backendFiles) {
			drift = append(drift, filepath.Join(backend, extra)+" (extra)")
		}
	}

	sort.Strings(drift)
	sort.Strings(stampOnly)

	return drift, stampOnly
}

// stampHashRe matches the schema hash inside any stamp shape this CLI has
// ever written: the current `schema-hash: sha256:<hex>` header line, the
// legacy `schema sha256:<hex>` header (v0.7.1 and earlier), and the
// x-zever-generated block of .json outputs.
var stampHashRe = regexp.MustCompile(`sha256:([0-9a-fA-F]+)`)

// normalizeStampVersion reduces content to its stamped schema hash plus the
// body with every leading stamp line removed, so a file stamped by a
// different zever release — or by an older header shape — compares equal to
// a fresh stamp when the schema hash and every other byte still match. Only
// leading lines are stamp lines (the stamp is always prepended first), so a
// backend's own generated headers deeper in the file still compare exactly.
// The caller reports such files as stampOnly: a note by default, a drift
// failure under --strict.
func normalizeStampVersion(path string, content []byte) []byte {
	if strings.HasSuffix(path, ".json") {
		var doc map[string]any

		if err := codec.Unmarshal(content, &doc); err != nil || doc == nil {
			return content
		}

		block, ok := doc["x-zever-generated"].(map[string]any)
		if !ok {
			return content
		}

		delete(block, "version")

		out, err := marshalStampJSON(doc)
		if err != nil {
			return content
		}

		return out
	}

	normalized := stripStampLines(content)

	return normalized
}

// stripStampLines reduces content to its stamped schema hash plus the body
// with every leading stamp line removed. Only leading lines qualify (the
// stamp is always prepended first), so a backend's own generated headers
// deeper in the file still compare exactly.
func stripStampLines(content []byte) []byte {
	text := string(content)
	hash := ""
	rest := text

	for i := 0; i < 2; i++ {
		head := rest
		tail := ""

		if idx := strings.IndexByte(rest, '\n'); idx >= 0 {
			head = rest[:idx]
			tail = rest[idx+1:]
		}

		if !strings.HasPrefix(head, "// Code generated by zever") && !strings.HasPrefix(head, "// schema-hash:") {
			break
		}

		if hash == "" {
			if m := stampHashRe.FindStringSubmatch(head); m != nil {
				hash = m[1]
			}
		}

		rest = tail

		if tail == "" {
			break
		}
	}

	if hash == "" {
		if m := stampHashRe.FindSubmatch(content); m != nil {
			hash = string(m[1])
		}
	}

	return []byte(hash + "\n" + rest)
}

// extraGeneratedFiles lists files present under dir (recursively) that the
// fresh compile did not produce. A missing dir yields none: every expected
// file is already reported missing by checkGeneratedOutputs.
func extraGeneratedFiles(dir string, fresh map[string][]byte) []string {
	var extra []string

	_ = filepath.WalkDir(dir, func(path string, entry os.DirEntry, err error) error {
		if err != nil || entry == nil || entry.IsDir() {
			return nil //nolint:nilerr // best-effort extras scan; expected files already report missing
		}

		rel, relErr := filepath.Rel(dir, path)
		if relErr != nil {
			return nil //nolint:nilerr // best-effort extras scan; unrelatable paths cannot be drift
		}

		if _, ok := fresh[filepath.ToSlash(rel)]; !ok {
			extra = append(extra, filepath.ToSlash(rel))
		}

		return nil
	})

	sort.Strings(extra)

	return extra
}
